import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { stringify } from 'yaml';
import type { Pack, ResolvedWorkflow } from '@sdlc/orchestrator';

export const GENERATED_MARKER = '<!-- generated by `sdlc build` from the pack and .sdlc/team/; do not edit -->';

const exists = (p: string) => stat(p).then(() => true, () => false);
const readOr = (p: string, fallback = '') => readFile(p, 'utf8').catch(() => fallback);

/** Neutral tool names → Copilot tool names in the agent file (plan §5 "Tools"). VERIFY in the Copilot SDK spike. */
export function copilotTools(neutral: string[]): string[] {
  const out = new Set<string>();
  for (const t of neutral) {
    if (t === 'read' || t === 'search') out.add('read').add('search');
    else if (t === 'edit') out.add('edit');
    else if (t.startsWith('shell:')) out.add('shell');
    else if (t === 'web') out.add('fetch');
    else if (t === 'ask_human') out.add('ask_human');
  }
  return [...out].sort();
}

/** `--allow-tool` patterns for the one-shot CLI fallback: `shell(mvn:*)` per configured program. */
export function cliAllowTools(neutral: string[], commands: Record<string, string>): string[] {
  const out = new Set<string>();
  for (const t of neutral) {
    if (t === 'edit') out.add('write');
    if (t.startsWith('shell:')) {
      const cmd = commands[t.slice(6)];
      const prog = cmd?.trim().split(/\s+/)[0];
      if (prog) out.add(`shell(${prog}:*)`);
    }
  }
  return [...out].sort();
}

export interface AgentFile {
  agent: string;
  path: string;
  content: string;
}

/**
 * `sdlc build` (plan §5): one `.github/agents/sdlc-<agent>.agent.md` per agent, made of the pack's common
 * rules and base prompt, the team's `.sdlc/team/agents/<agent>/instructions.md`, and the list of the
 * agent's skills. The tool list is the union of the agent's contracts' tools.
 */
export async function buildAgentFiles(pack: Pack, workflow: ResolvedWorkflow, teamDir: string): Promise<AgentFile[]> {
  if (!pack.dir || !pack.agents) throw new Error('pack must be loaded from disk (loadPack) to build agent files');
  const common = await readOr(join(pack.dir, 'agents', '_common.md'));
  const files: AgentFile[] = [];
  for (const [agent, meta] of Object.entries(pack.agents)) {
    const contracts = workflow.contracts.filter((c) => c.contract.agent === agent);
    const tools = copilotTools([...new Set(contracts.flatMap((c) => c.contract.tools))]);
    const ov = workflow.overlay.agents[agent] ?? {};
    const base = await readOr(join(pack.dir, meta.prompt));
    const teamInstr = await readOr(join(teamDir, 'agents', agent, ov.instructions ?? 'instructions.md'));
    const skills = await listSkills(join(teamDir, 'agents', agent, 'skills'));
    const front = {
      name: `sdlc-${agent}`,
      description: `${agent} agent of the ${pack.name}@${pack.major} workflow (${workflow.overlay.team}). Run by the sdlc engine.`,
      ...(tools.length ? { tools } : {}),
      ...(ov.model ? { model: ov.model } : {}),
    };
    const body = [
      GENERATED_MARKER,
      '',
      base.trim(),
      '',
      common.trim(),
      ...(teamInstr.trim() ? ['', `## Team instructions (${workflow.overlay.team})`, '', teamInstr.trim()] : []),
      ...(skills.length ? ['', '## Skills', '', ...skills.map((s) => `- ${s}`)] : []),
      '',
    ].join('\n');
    files.push({ agent, path: `.github/agents/sdlc-${agent}.agent.md`, content: `---\n${stringify(front).trimEnd()}\n---\n${body}` });
  }
  return files;
}

async function listSkills(dir: string): Promise<string[]> {
  if (!(await exists(dir))) return [];
  const out: string[] = [];
  for (const d of (await readdir(dir)).sort()) if (await exists(join(dir, d, 'SKILL.md'))) out.push(d);
  return out;
}

/** Writes the agent files into a directory (the workspace repo or a worktree) and removes stale `sdlc-*` ones. */
export async function writeAgentFiles(root: string, files: AgentFile[]): Promise<string[]> {
  const dir = join(root, '.github', 'agents');
  await mkdir(dir, { recursive: true });
  const keep = new Set(files.map((f) => f.path.split('/').pop()));
  for (const f of await readdir(dir)) if (f.startsWith('sdlc-') && f.endsWith('.agent.md') && !keep.has(f)) await rm(join(dir, f));
  for (const f of files) await writeFile(join(root, f.path), f.content, 'utf8');
  return files.map((f) => f.path);
}

/**
 * Installs one agent into an attempt's worktree before its session (plan §5 "Skills"): its agent file,
 * and only that agent's skills, under `.github/skills/`.
 */
export async function installAgent(files: AgentFile[], teamDir: string, agent: string, workdir: string): Promise<void> {
  const f = files.find((x) => x.agent === agent);
  if (!f) throw new Error(`no agent file for ${agent}; run sdlc build`);
  await mkdir(join(workdir, '.github', 'agents'), { recursive: true });
  await writeFile(join(workdir, f.path), f.content, 'utf8');
  const skills = join(teamDir, 'agents', agent, 'skills');
  await rm(join(workdir, '.github', 'skills'), { recursive: true, force: true });
  if (await exists(skills)) await cp(skills, join(workdir, '.github', 'skills'), { recursive: true });
}
